// HELPER FUNCTIONS
// ============================================================

export function getCareerData(career) {
  if (!career) {
    return null;
  }

  return careerData[career] || null;
}


export function getCareerNames() {
  return Object.keys(careerData);
}


export function findCareerData(career) {
  if (!career) {
    return null;
  }

  const normalizedCareer =
    String(career)
      .trim()
      .toLowerCase();

  const exactMatch =
    Object.keys(careerData).find(
      (name) =>
        name.toLowerCase() ===
        normalizedCareer
    );

  if (exactMatch) {
    return careerData[exactMatch];
  }

  const partialMatch =
    Object.keys(careerData).find(
      (name) =>
        normalizedCareer.includes(
          name.toLowerCase()
        ) ||
        name
          .toLowerCase()
          .includes(normalizedCareer)
    );

  return partialMatch
    ? careerData[partialMatch]
    : null;
}


export default careerData;